//! Generate `data/synonyms.yaml` from `data/keywords.yaml` and an Open
//! English WordNet JSON release:
//!
//! ```sh
//! cargo run -p leaf-common --features serde --example build-synonyms -- \
//!     english-wordnet-2025-json.zip
//! ```
//!
//! For each keyword, the members of its chosen senses (minus `exclude`) are
//! inflected (plural, singular, hyphen-less, `related-` forms) and added with
//! its `extra` spellings. A spelling that would mean two keywords, or is a
//! keyword itself, is dropped and reported.

use leaf_common::dictionary::{Dictionary, DictionaryKey};
use serde::Deserialize;
use std::collections::{BTreeMap, BTreeSet, HashMap, HashSet};
use std::fs::File;
use std::io::Read;
use std::path::Path;

const SOURCE: &str = "Synonyms selected from Open English WordNet 2025 \
(https://github.com/globalwordnet/english-wordnet, CC BY 4.0), derived from Princeton WordNet \
(WordNet License, https://wordnet.princeton.edu/license-and-commercial-use)";

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Keywords {
    keys: BTreeMap<String, KeyEntry>,
    labels: BTreeMap<String, BTreeMap<String, Senses>>,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct KeyEntry {
    description: String,
    values: String,
    #[serde(default)]
    map: Option<String>,
    #[serde(default)]
    single: bool,
    /// Synonyms also apply with a `related-` prefix.
    #[serde(default)]
    related: bool,
    #[serde(flatten)]
    senses: Senses,
}

#[derive(Deserialize, Default)]
struct Senses {
    #[serde(default)]
    senses: Vec<String>,
    #[serde(default)]
    exclude: Vec<String>,
    #[serde(default)]
    extra: Vec<String>,
}

#[derive(Deserialize)]
struct Synset {
    members: Vec<String>,
}

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let release = std::env::args()
        .nth(1)
        .ok_or("usage: build-synonyms <english-wordnet-json.zip>")?;
    let data = Path::new(env!("CARGO_MANIFEST_DIR")).join("data");
    let keywords: Keywords =
        serde_saphyr::from_str(&std::fs::read_to_string(data.join("keywords.yaml"))?)?;
    let (synsets, lemmas) = read_release(Path::new(&release))?;

    let mut report = Vec::new();
    let key_spellings: BTreeMap<String, BTreeSet<String>> = keywords
        .keys
        .iter()
        .map(|(key, entry)| {
            let others = keywords
                .keys
                .keys()
                .filter(|k| *k != key)
                .cloned()
                .collect();
            Ok((
                key.clone(),
                spellings(&entry.senses, entry.related, &synsets, &lemmas, &others)?,
            ))
        })
        .collect::<Result<_, String>>()?;
    let mut keys = BTreeMap::new();
    for (key, synonyms) in unambiguous(&key_spellings, "keys", &mut report) {
        let entry = &keywords.keys[&key];
        keys.insert(
            key,
            DictionaryKey {
                description: entry.description.clone(),
                values: entry.values.clone(),
                map: entry.map.clone(),
                single: entry.single,
                synonyms,
            },
        );
    }
    let mut labels = BTreeMap::new();
    for (key, entries) in &keywords.labels {
        let label_spellings: BTreeMap<String, BTreeSet<String>> = entries
            .iter()
            .map(|(label, senses)| {
                let others = entries.keys().filter(|l| *l != label).cloned().collect();
                Ok((
                    label.clone(),
                    spellings(senses, false, &synsets, &lemmas, &others)?,
                ))
            })
            .collect::<Result<_, String>>()?;
        labels.insert(
            key.clone(),
            unambiguous(&label_spellings, &format!("labels of {key}"), &mut report)
                .into_iter()
                .collect(),
        );
    }
    let dictionary = Dictionary {
        source: SOURCE.into(),
        keys,
        labels,
    };
    let mut text = String::from(
        "# Generated by `cargo run -p leaf-common --features serde --example build-synonyms`\n\
         # from data/keywords.yaml; do not edit. See `source` for attribution and licenses.\n",
    );
    for line in &report {
        text.push_str(&format!("# {line}\n"));
    }
    text.push_str(&serde_saphyr::to_string(&dictionary)?);
    std::fs::write(data.join("synonyms.yaml"), text)?;
    for line in &report {
        eprintln!("{line}");
    }
    let total: usize = dictionary
        .keys
        .values()
        .map(|k| k.synonyms.len())
        .sum::<usize>()
        + dictionary
            .labels
            .values()
            .flat_map(|l| l.values())
            .map(Vec::len)
            .sum::<usize>();
    eprintln!(
        "wrote data/synonyms.yaml: {} keys, {total} synonyms",
        dictionary.keys.len()
    );
    Ok(())
}

/// Synsets by ID (`00007846-n`) and every lemma of a release.
type Release = (HashMap<String, Synset>, HashSet<String>);

/// Every synset of the release by ID, and every lemma.
fn read_release(release: &Path) -> Result<Release, Box<dyn std::error::Error>> {
    let mut archive = zip::ZipArchive::new(File::open(release)?)?;
    let names: Vec<String> = archive
        .file_names()
        .collect::<Result<Vec<_>, _>>()?
        .into_iter()
        .filter(|name| {
            ["noun.", "adj.", "adv.", "verb.", "entries-"]
                .iter()
                .any(|prefix| name.starts_with(prefix))
                && name.ends_with(".json")
        })
        .map(String::from)
        .collect();
    let mut synsets = HashMap::new();
    let mut lemmas = HashSet::new();
    for name in names {
        let mut text = String::new();
        archive.by_name(&name)?.read_to_string(&mut text)?;
        if name.starts_with("entries-") {
            let entries: HashMap<String, serde::de::IgnoredAny> = serde_json::from_str(&text)?;
            lemmas.extend(entries.into_keys().map(|lemma| lemma.to_lowercase()));
        } else {
            let file: HashMap<String, Synset> = serde_json::from_str(&text)?;
            synsets.extend(file);
        }
    }
    Ok((synsets, lemmas))
}

/// All spellings of a keyword: its senses' members (inflected) and extras.
/// A member that is another keyword (`friend` in the `acquaintance` sense)
/// is skipped with all its forms, which belong to that keyword.
fn spellings(
    senses: &Senses,
    related: bool,
    synsets: &HashMap<String, Synset>,
    lemmas: &HashSet<String>,
    other_keywords: &BTreeSet<String>,
) -> Result<BTreeSet<String>, String> {
    let excluded: Vec<String> = senses.exclude.iter().map(|w| w.to_lowercase()).collect();
    let mut found = BTreeSet::new();
    for id in &senses.senses {
        let synset = synsets
            .get(id)
            .ok_or_else(|| format!("sense {id} is not in this WordNet release"))?;
        for member in &synset.members {
            if excluded.contains(&member.to_lowercase())
                || other_keywords.contains(&slug::slugify(member))
            {
                continue;
            }
            for form in inflections(member, lemmas) {
                if related {
                    found.insert(format!("related-{form}"));
                }
                found.insert(form);
            }
        }
    }
    found.extend(senses.extra.iter().map(slug::slugify));
    Ok(found)
}

/// Singular, plural and hyphen-less slugs of a word or phrase. A singular is
/// kept only if WordNet knows it (`cognomen` is not singularized to
/// `cognoman`); WordNet has no plurals, so plurals are kept.
fn inflections(word: &str, lemmas: &HashSet<String>) -> BTreeSet<String> {
    let singular = pluralizer::pluralize(word, 1, false);
    let mut forms: BTreeSet<String> = [word.to_string(), pluralizer::pluralize(word, 2, false)]
        .into_iter()
        .chain(
            lemmas
                .contains(&singular.to_lowercase())
                .then_some(singular),
        )
        .map(slug::slugify)
        .collect();
    if word.contains('-') {
        let joined: Vec<String> = forms.iter().map(|f| f.replace('-', "")).collect();
        forms.extend(joined);
    }
    forms
}

/// Each keyword's spellings, minus keywords themselves and spellings shared
/// by two keywords (reported).
fn unambiguous(
    spellings: &BTreeMap<String, BTreeSet<String>>,
    what: &str,
    report: &mut Vec<String>,
) -> BTreeMap<String, Vec<String>> {
    let mut owners: BTreeMap<&str, BTreeSet<&str>> = BTreeMap::new();
    for (keyword, forms) in spellings {
        for form in forms {
            owners.entry(form).or_default().insert(keyword);
        }
    }
    spellings
        .iter()
        .map(|(keyword, forms)| {
            let kept = forms
                .iter()
                .filter(|form| {
                    if *form == keyword {
                        return false;
                    }
                    if spellings.contains_key(*form) {
                        report.push(format!(
                            "{what}: `{form}` is a keyword itself, not a synonym of `{keyword}`"
                        ));
                        return false;
                    }
                    let shared = &owners[form.as_str()];
                    if shared.len() > 1 && shared.first() == Some(&keyword.as_str()) {
                        let names: Vec<&str> = shared.iter().copied().collect();
                        report.push(format!(
                            "{what}: dropped `{form}`, which could mean {}",
                            names.join(" or ")
                        ));
                    }
                    shared.len() == 1
                })
                .cloned()
                .collect();
            (keyword.clone(), kept)
        })
        .collect()
}
